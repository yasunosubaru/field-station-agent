#!/usr/bin/env node
/**
 * Extract the literal lookup tables consumed by the status tiles.
 *
 * The shipped NovatelIdConstants.js is the authority for these maps.  The
 * generated TypeScript file contains data only, so the runtime has no
 * dependency on 01_解包/ and no build step.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const sourcePath = join(root, '01_解包', 'app', 'model', 'NovatelIdConstants.js');
const outputPath = join(
  here,
  '..',
  'packages',
  'protocol',
  'src',
  'generated-status-tables.ts',
);
const source = readFileSync(sourcePath, 'utf8');

function literalAfter(prefix) {
  const marker = `NovatelIdConstants.${prefix}`;
  const markerAt = source.indexOf(marker);
  if (markerAt < 0) throw new Error(`missing ${marker}`);
  const equalsAt = source.indexOf('=', markerAt + marker.length);
  if (equalsAt < 0) throw new Error(`missing '=' after ${marker}`);
  let start = equalsAt + 1;
  while (/\s/.test(source[start])) start += 1;
  const open = source[start];
  const close = open === '{' ? '}' : open === '[' ? ']' : '';
  if (!close) throw new Error(`${marker} is not an object or array`);
  let depth = 0;
  let quote = '';
  let escaped = false;
  for (let index = start; index < source.length; index += 1) {
    const char = source[index];
    if (quote) {
      if (escaped) escaped = false;
      else if (char === '\\') escaped = true;
      else if (char === quote) quote = '';
      continue;
    }
    if (char === '"' || char === "'" || char === '`') {
      quote = char;
      continue;
    }
    if (char === open) depth += 1;
    else if (char === close) {
      depth -= 1;
      if (depth === 0) return source.slice(start, index + 1);
    }
  }
  throw new Error(`unterminated ${marker}`);
}

function value(name) {
  return Function(`"use strict"; return (${literalAfter(name)});`)();
}

const names = [
  'satvisConstellationMap',
  'giiiSatvisConstellationMap',
  'trackstatConstellationMap',
  'ConstellationIdConstants',
  'ConstellationWiseSingalEnums',
  'trackstatSingalEnums',
  'updatedChanConfigListSignalType',
  'chanConfigListSignalType',
  'updatedSignalTypeDesc',
  'signalTypeDesc',
  'giiiConstellationWiseSingalEnums',
  'giiitrackstatConstellationMap',
];

const tables = Object.fromEntries(names.map((name) => [name, value(name)]));
const header = [
  '/**',
  ' * Generated by tools/gen_status_tables.js from the shipped',
  ' * 01_解包/app/model/NovatelIdConstants.js. Do not edit by hand.',
  ' */',
  '',
];
for (const [name, table] of Object.entries(tables)) {
  header.push(`export const ${name} = ${JSON.stringify(table, null, 2)} as const;`, '');
}
writeFileSync(outputPath, header.join('\n'));
console.log(`wrote ${outputPath}`);
