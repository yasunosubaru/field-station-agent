// Extract the two language dictionaries we support (en + cn) from the shipped language files.
//
//   node tools/gen_language_dicts.js
//
// Inputs : 01_解包/app/view/languageSupport/{en,cn}.js   (read-only evidence)
// Outputs: 04_重实现/packages/view/src/language/dict-en.ts
//          04_重实现/packages/view/src/language/dict-cn.ts
//
// The shipped files are plain `Language.EN = { 'KEY': 'text', … };` literals followed by
// `jsIn.addDict(Language.EN)`. They are pure data, so evaluating the literal in a sandbox is exact
// and keeps us from hand-transcribing ~1 900 keys.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..');
const support = path.join(root, '01_解包', 'app', 'view', 'languageSupport');
const outDir = path.join(root, '04_重实现', 'packages', 'view', 'src', 'language');

function extractDict(file, constName) {
  const source = fs.readFileSync(file, 'utf8');
  const start = source.search(new RegExp('Language\\.' + constName + '\\s*=\\s*\\{'));
  if (start < 0) throw new Error(`${constName} literal not found in ${file}`);
  const open = source.indexOf('{', start);
  let depth = 0;
  let quote = '';
  let end = -1;
  for (let i = open; i < source.length; i++) {
    const char = source[i];
    if (quote) {
      if (char === '\\') i++;
      else if (char === quote) quote = '';
      continue;
    }
    if (char === "'" || char === '"' || char === '`') quote = char;
    else if (char === '{') depth++;
    else if (char === '}') {
      depth--;
      if (depth === 0) { end = i; break; }
    }
  }
  if (end < 0) throw new Error(`${constName}: unbalanced braces`);
  const literal = source.slice(open, end + 1);
  const sandbox = {};
  vm.createContext(sandbox);
  const value = vm.runInContext('(' + literal + ')', sandbox, { timeout: 5000 });
  // drop the inherited/undefined noise some files carry
  const clean = {};
  for (const [key, text] of Object.entries(value)) {
    if (typeof text === 'string') clean[key] = text;
  }
  return clean;
}

const en = extractDict(path.join(support, 'en.js'), 'EN');
const cn = extractDict(path.join(support, 'cn.js'), 'CN');

const emit = (name) =>
  `// GENERATED by tools/gen_language_dicts.js — do not edit by hand.\n` +
  `// Source: 01_解包/app/view/languageSupport/${name}.js (Language.${name.toUpperCase()}).\n` +
  `const dict: Record<string, string> = ${JSON.stringify(name === 'en' ? en : cn, null, 1)};\n\n` +
  `export default dict;\n`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'dict-en.ts'), emit('en'));
fs.writeFileSync(path.join(outDir, 'dict-cn.ts'), emit('cn'));

console.log(`en: ${Object.keys(en).length} keys`);
console.log(`cn: ${Object.keys(cn).length} keys`);
