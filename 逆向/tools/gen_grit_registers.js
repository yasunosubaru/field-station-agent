// Generate the GRIT registers from the shipped GRIT façade.
//
//   node tools/gen_grit_registers.js
//
// Inputs : 01_解包/app/view/GRIT/gritJarvisInterface.js   (read-only evidence)
// Outputs: 04_重实现/packages/view/data/grit-comp-register.json
//          04_重实现/packages/view/data/grit-comp-logs-register.json
//          04_重实现/packages/view/src/grit/register-data.ts
//
// The literals are transcribed by machine on purpose: §3.1/§3.2 of 05_GRIT-Monitor.md list 50+
// message ids and 14 components, and a hand copy drifts the moment the bundle changes.

const fs = require('fs');
const path = require('path');

const here = path.resolve(__dirname, '..');
const source = path.join(here, '01_解包', 'app', 'view', 'GRIT', 'gritJarvisInterface.js');
const dataDir = path.join(here, '04_重实现', 'packages', 'view', 'data');
const srcDir = path.join(here, '04_重实现', 'packages', 'view', 'src', 'grit');

/** Pull `<name> = { … }` out of the façade by brace matching, then evaluate it. */
function extractLiteral(text, name) {
  const start = text.search(new RegExp('(?:const|let|var)\\s+' + name + '\\s*=\\s*\\{'));
  if (start < 0) throw new Error(`${name} not found`);
  const open = text.indexOf('{', start);
  let depth = 0;
  let quote = '';
  for (let i = open; i < text.length; i++) {
    const c = text[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = '';
      continue;
    }
    if (c === "'" || c === '"' || c === '`') quote = c;
    else if (c === '{') depth++;
    else if (c === '}') {
      depth--;
      if (depth === 0) return text.slice(open, i + 1);
    }
  }
  throw new Error(`${name}: unbalanced braces`);
}

const sourceText = fs.readFileSync(source, 'utf8');
const compRegister = eval('(' + extractLiteral(sourceText, 'gritCompRegister') + ')');
const logsRegister = eval('(' + extractLiteral(sourceText, 'gritCompLogsRegister') + ')');

const normaliseLogs = (register) => {
  const out = {};
  for (const [component, logs] of Object.entries(register)) {
    out[component] = {};
    for (const [key, spec] of Object.entries(logs)) out[component][key] = String(spec).replace(/\s+/g, '');
  }
  return out;
};

const normalisedLogs = normaliseLogs(logsRegister);

fs.mkdirSync(dataDir, { recursive: true });
fs.mkdirSync(srcDir, { recursive: true });
fs.writeFileSync(path.join(dataDir, 'grit-comp-register.json'), JSON.stringify(compRegister, null, 2) + '\n');
fs.writeFileSync(path.join(dataDir, 'grit-comp-logs-register.json'), JSON.stringify(normalisedLogs, null, 2) + '\n');

const header = `// GENERATED by tools/gen_grit_registers.js — do not edit by hand.
// Source: 01_解包/app/view/GRIT/gritJarvisInterface.js (gritCompRegister / gritCompLogsRegister).
`;
const literal = (value) => JSON.stringify(value, null, 2).replace(/"([^"]+)":/g, "'$1':");
fs.writeFileSync(
  path.join(srcDir, 'register-data.ts'),
  header +
    `export const GRIT_COMP_REGISTER: Record<string, Record<string, string>> = ${literal(compRegister)};\n\n` +
    `export const GRIT_LOG_REGISTER: Record<string, Record<string, string>> = ${literal(normalisedLogs)};\n`,
);

const components = Object.keys(normalisedLogs);
const rows = components.reduce((total, component) => total + Object.keys(normalisedLogs[component]).length, 0);
console.log(`grit registers: ${components.length} components, ${rows} log rows`);
console.log(`  ${path.relative(here, path.join(dataDir, 'grit-comp-register.json'))}`);
console.log(`  ${path.relative(here, path.join(dataDir, 'grit-comp-logs-register.json'))}`);
console.log(`  ${path.relative(here, path.join(srcDir, 'register-data.ts'))}`);
